-- Pronunciation dictionary shared by every agent: how the voice says a word the agent writes
-- (e.g. "CRM" -> "סי. אָר. אֶם."). Edited in Admin -> Settings -> Pronunciation; sent to the voice
-- provider as one dictionary of alias rules and attached to every agent's speech settings.
-- Matching at the provider is case-sensitive; the sync adds the common case forms.
create table public.pronunciation_rules (
  id uuid primary key default gen_random_uuid(),
  -- the word as the agent writes it
  term text not null check (length(trim(term)) > 0),
  -- how to say it (usually Hebrew with niqqud)
  say text not null check (length(trim(say)) > 0),
  -- free note for the admin (e.g. a Hebrew alternative); never sent anywhere
  note text not null default '',
  category text not null default '',
  enabled boolean not null default true,
  position integer not null default 0,
  created_at timestamptz not null default now()
);
create unique index pronunciation_rules_term on public.pronunciation_rules (lower(term));
-- Admin only (service role); no grants to clients.
alter table public.pronunciation_rules enable row level security;

-- The dictionary as it was last sent to the provider.
alter table public.system_settings
  add column pronunciation_dict_id text,
  add column pronunciation_dict_version text,
  add column pronunciation_dict_hash text;

